# PUBLIC_INTERFACE
def connect():
    """Open a foreign-key-enforcing connection; caller owns its lifetime."""
    if is_pg():
        return _connect_pg()
    conn = sqlite3.connect(db_path(), timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


_POOL: dict = {}
_POOL_LOCK = threading.Lock()
_POOL_MAX = 8
_POOL_PING_AFTER_S = 10


def _from_pool(key):
    """Reuse an idle connection; ping it first if it has been idle a while (the pooler drops idle ones)."""
    while True:
        with _POOL_LOCK:
            idle = _POOL.get(key)
            if not idle:
                return None
            raw, since = idle.pop()
        try:
            if not raw.closed:
                if time.monotonic() - since > _POOL_PING_AFTER_S:
                    raw.execute("SELECT 1")
                    raw.rollback()
                return raw
        except psycopg.Error:
            pass
        try:
            raw.close()
        except psycopg.Error:
            pass


def _connect_pg() -> PgConnection:
    if psycopg is None:
        raise RuntimeError("POC_DB=postgres needs the psycopg package (pip install 'psycopg[binary]')")
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise RuntimeError("POC_DB=postgres needs DATABASE_URL (Supabase session pooler connection string)")
    schema = os.environ.get("POC_PG_SCHEMA")  # isolated schema for tests; default is the project schema
    if schema and not re.fullmatch(r"[a-z_][a-z0-9_]*", schema):
        raise RuntimeError("POC_PG_SCHEMA must be a simple lowercase identifier")
    key = (url, schema)
    raw = _from_pool(key)
    if raw is None:
        raw = psycopg.connect(url, row_factory=_row_factory, connect_timeout=15)
        raw.adapters.register_dumper(bool, _BoolAsInt)
        if schema:
            raw.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
            raw.execute(f'SET search_path TO "{schema}"')
            raw.commit()
    return PgConnection(raw, key)


# PUBLIC_INTERFACE
def pipeline(conn):
    """Context manager that batches statements on Postgres and does nothing on SQLite."""
    return conn.pipeline() if is_pg() else nullcontext()


# PUBLIC_INTERFACE
def table_names(conn) -> list:
    """Names of the PoC tables in the active database (bookkeeping tables excluded)."""
    if is_pg():
        rows = conn.execute("SELECT table_name FROM information_schema.tables "
                            "WHERE table_schema=current_schema() AND table_type='BASE TABLE' "
                            "AND table_name<>'schema_meta'")
    else:
        rows = conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")
    return sorted(r[0] for r in rows)


# PUBLIC_INTERFACE
def columns(conn, table: str) -> set:
    """Column names of ``table``."""
    if is_pg():
        return {r[0] for r in conn.execute("SELECT column_name FROM information_schema.columns "
                                           "WHERE table_schema=current_schema() AND table_name=?", (table,))}
    return {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}


# PUBLIC_INTERFACE
def get_version(conn) -> int:
    """Schema version: SQLite ``user_version`` or the Postgres ``schema_meta`` row."""
    if is_pg():
        conn.executescript("CREATE TABLE IF NOT EXISTS schema_meta(key TEXT PRIMARY KEY, value TEXT)")
        row = conn.execute("SELECT value FROM schema_meta WHERE key='user_version'").fetchone()
        return int(row[0]) if row else 0
    return conn.execute("PRAGMA user_version").fetchone()[0]


# PUBLIC_INTERFACE
def set_version(conn, version: int) -> None:
    """Record the schema version."""
    if is_pg():
        conn.execute("INSERT INTO schema_meta(key,value) VALUES('user_version',?) "
                     "ON CONFLICT(key) DO UPDATE SET value=excluded.value", (str(int(version)),))
    else:
        conn.execute(f"PRAGMA user_version={int(version)}")


# PUBLIC_INTERFACE
def config():
    """Read the single source of provisional business configuration."""
    return json.loads((ROOT / "config.json").read_text(encoding="utf-8"))


# PUBLIC_INTERFACE
def seed_anchor() -> datetime:
    """Return the fixed anchor date used for seeded data.

    ``POC_SEED_ANCHOR`` (ISO date-time or ``today``) overrides ``seed.anchor_date``
    in config.json. A fixed anchor keeps seeded data identical on every day.
    """
    raw = os.environ.get("POC_SEED_ANCHOR") or config()["seed"]["anchor_date"]
    if raw == "today":
        return datetime.now(timezone.utc).replace(hour=12, minute=0, second=0, microsecond=0)
    parsed = datetime.fromisoformat(raw)
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


# PUBLIC_INTERFACE
def reference_now() -> datetime:
    """Return the 'current' time used by business rules such as repeat detection.

    ``POC_CLOCK_MODE`` (``fixed`` or ``real``) overrides ``seed.clock_mode``. In
    ``fixed`` mode the seed anchor is used so seeded repeat scenarios stay valid.
    """
    mode = os.environ.get("POC_CLOCK_MODE") or config()["seed"].get("clock_mode", "fixed")
    return seed_anchor() if mode == "fixed" else datetime.now(timezone.utc)


# PUBLIC_INTERFACE
def initialize(seed: bool = False):
    """Create the schema (v1 base plus migrations) and optionally seed if empty.

    Seeding lives in ``backend.seed``; it is never run destructively from here.
    """
    from . import migrations

    with connect() as conn:
        conn.executescript(BASE_SCHEMA)
        if get_version(conn) == 0:
            set_version(conn, 1)
        migrations.migrate(conn)
    if seed:
        from . import seed as seed_module

        seed_module.seed_if_empty()
