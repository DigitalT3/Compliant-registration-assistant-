# PUBLIC_INTERFACE
def is_pg() -> bool:
    """True when the Postgres backend is selected explicitly (``POC_DB=postgres``).

    DATABASE_URL alone never switches the backend, so tests and scripts cannot reach a hosted
    database by accident.
    """
    return (os.environ.get("POC_DB") or "sqlite").lower() in ("postgres", "postgresql", "supabase")


DBError = (sqlite3.Error,) + ((psycopg.Error,) if psycopg else ())

_GLOB = re.compile(r"(\w+)\s+GLOB\s+'([^']*)'", re.I)


def _translate(sql: str, params: bool = True) -> str | None:
    """Rewrite the SQLite dialect used by this codebase for Postgres; None means 'skip this statement'."""
    stripped = sql.strip()
    head = stripped.upper()
    if head.startswith("PRAGMA"):
        return None
    if head == "BEGIN IMMEDIATE":  # serialise id allocation, like SQLite's write lock
        return "LOCK TABLE complaints IN SHARE ROW EXCLUSIVE MODE"
    sql = _GLOB.sub(lambda m: f"{m.group(1)} ~ '^{m.group(2).replace('*', '.*')}$'", sql)
    sql = re.sub(r"\bIS NOT \?", "IS DISTINCT FROM ?", sql)        # SQLite's null-safe comparison
    sql = re.sub(r"\bIS \?", "IS NOT DISTINCT FROM ?", sql)
    sql = re.sub(r"INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    if params:
        sql = sql.replace("%", "%%").replace("?", "%s")
    return sql


if psycopg:
    class _PgRow(tuple):
        """Row readable by index and by column name, like sqlite3.Row."""

        def __new__(cls, names, values):
            row = super().__new__(cls, values)
            row._names = names
            return row

        def __getitem__(self, key):
            if isinstance(key, str):
                return super().__getitem__(self._names.index(key))
            return super().__getitem__(key)

        def keys(self):
            return list(self._names)

    def _row_factory(cursor):
        names = [c.name for c in cursor.description] if cursor.description else []
        return lambda values: _PgRow(names, values)

    class _BoolAsInt(Dumper):
        """The schema stores flags as INTEGER (SQLite style), so send Python bools as 0/1."""
        oid = psycopg.postgres.types["int2"].oid

        def dump(self, obj):
            return b"1" if obj else b"0"


class PgConnection:
    """Minimal sqlite3-compatible wrapper over a psycopg connection (execute, commit, `with`)."""

    def __init__(self, raw, key=None):
        self._c = raw
        self._key = key

    def execute(self, sql, params=()):
        stmt = _translate(sql)
        if stmt is None:
            return self._c.cursor().execute("SELECT 1")
        return self._c.cursor().execute(stmt, tuple(params) if params is not None else ())

    def executescript(self, script: str) -> None:
        self._c.execute(_translate(script, params=False))

    def pipeline(self):
        """Send many statements without waiting for each reply (a big win on a remote database)."""
        return self._c.pipeline()

    def commit(self):
        self._c.commit()

    def rollback(self):
        self._c.rollback()

    def close(self):
        """Return the connection to the pool (a fresh TCP/TLS connect to the pooler takes over a second)."""
        raw, self._c = self._c, None
        if raw is None:
            return
        try:
            raw.rollback()
            if not raw.closed and self._key is not None:
                with _POOL_LOCK:
                    idle = _POOL.setdefault(self._key, [])
                    if len(idle) < _POOL_MAX:
                        idle.append((raw, time.monotonic()))
                        return
        except psycopg.Error:
            pass
        try:
            raw.close()
        except psycopg.Error:
            pass

    def __enter__(self):
        return self

    def __exit__(self, exc_type, *_):
        self.rollback() if exc_type else self.commit()
        return False


