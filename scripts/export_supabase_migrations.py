"""Export the schema as standard Supabase migration files (supabase/migrations/*.sql).

The app applies its own versioned migrations (backend/migrations.py). This script replays them
against a recorder instead of a database and writes the Postgres SQL they would run, so the same
schema can be rebuilt with the Supabase CLI (`supabase db push`) and shows up in the dashboard's
Database > Migrations page. The files are generated: change backend/migrations.py, then re-run.

  python -m scripts.export_supabase_migrations              # write the files
  python -m scripts.export_supabase_migrations --register   # also record them as applied in Supabase
"""
import argparse
import os
import re
import sys
from pathlib import Path

from backend import db, migrations

OUT = Path(__file__).resolve().parents[1] / "supabase" / "migrations"
STAMP = "20261029"  # fixed: file names must not change between runs
HEADER = "-- Generated by scripts/export_supabase_migrations.py from backend/migrations.py. Do not edit by hand.\n\n"
NAMES = {1: "base_schema", 2: "poc_entities", 3: "form_fields", 4: "root_cause_category", 5: "user_test_support", 6: "employee_accounts", 7: "forced_password_change"}


class _Recorder:
    """Stands in for a connection: collects the translated SQL instead of running it."""

    def __init__(self):
        self.statements = []

    def execute(self, sql, params=()):
        self._add(sql)
        return self

    def executescript(self, script):
        self._add(script)

    def _add(self, sql):
        translated = db._translate(sql, params=False)
        if translated:
            translated = re.sub(r"ADD COLUMN (?!IF NOT EXISTS)", "ADD COLUMN IF NOT EXISTS ", translated)
            self.statements.append(translated.strip().rstrip(";") + ";")

    def commit(self):
        pass


def build() -> dict:
    """Return {file name: SQL text} for every migration plus the closing hardening step."""
    original = db.columns
    db.columns = lambda conn, table: set()  # a fresh database has no columns yet
    try:
        files, tables = {}, []
        steps = {1: lambda r: r.executescript(db.BASE_SCHEMA), **migrations.MIGRATIONS}
        for version in sorted(steps):
            rec = _Recorder()
            steps[version](rec)
            body = "\n\n".join(rec.statements)
            tables += re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", body)
            files[f"{STAMP}{version:06d}_{NAMES[version]}.sql"] = HEADER + body + "\n"
    finally:
        db.columns = original
    last = max(migrations.MIGRATIONS)
    rls = "\n".join(f'ALTER TABLE "{t}" ENABLE ROW LEVEL SECURITY;' for t in tables + ["schema_meta"])
    files[f"{STAMP}{last + 1:06d}_security_and_version.sql"] = HEADER + (
        "-- Supabase exposes public tables through its REST API. With row-level security on and no policies,\n"
        "-- the anon and authenticated roles can read and write nothing; the backend connects as the owner.\n"
        "CREATE TABLE IF NOT EXISTS schema_meta(key TEXT PRIMARY KEY, value TEXT);\n"
        f"INSERT INTO schema_meta(key,value) VALUES('user_version','{last}')\n"
        "  ON CONFLICT(key) DO UPDATE SET value=excluded.value;\n\n" + rls + "\n")
    return files


def write() -> list:
    OUT.mkdir(parents=True, exist_ok=True)
    files = build()
    for stale in OUT.glob("*.sql"):
        if stale.name not in files:
            stale.unlink()
    for name, sql in files.items():
        (OUT / name).write_text(sql, encoding="utf-8")
    return sorted(files)


def register() -> int:
    """Record the files as applied in Supabase's migration history (what `supabase db push` would do).

    Uses the CLI's own table definition. The statements are already applied (the app created the
    schema), so nothing is executed here: only the history rows are written.
    """
    import psycopg

    url = os.environ.get("DATABASE_URL")
    if not url:
        raise SystemExit("DATABASE_URL is not set")
    files = build()
    with psycopg.connect(url, connect_timeout=15) as conn:
        conn.execute("CREATE SCHEMA IF NOT EXISTS supabase_migrations")
        conn.execute("CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations("
                     "version text NOT NULL PRIMARY KEY, statements text[], name text)")
        for name, sql in files.items():
            version, _, rest = name[:-4].partition("_")
            conn.execute("INSERT INTO supabase_migrations.schema_migrations(version,statements,name) "
                         "VALUES(%s,%s,%s) ON CONFLICT(version) DO NOTHING", (version, [sql], rest))
    return len(files)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--register", action="store_true", help="record the files as applied in Supabase")
    args = ap.parse_args(argv)
    for name in write():
        print("wrote supabase/migrations/" + name)
    if args.register:
        print(f"registered {register()} migrations in supabase_migrations.schema_migrations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
